"""Write examples/graph-sample.md: the review's dependency graph for dummy
projects of growing size, to see where it stops being readable (issue #10).
Run from the repo root:
    python3 examples/graph_sample.py
"""
import pathlib
import random
import sys
import tempfile

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
import pmtrack  # noqa: E402

MERMAID_LIMIT = 50000   # Forgejo's default MERMAID_MAX_SOURCE_CHARACTERS
VERBS = ["Add", "Fix", "Write", "Check", "Move", "Split", "Speed up", "Document", "Test", "Drop"]
NOUNS = ["login form", "token store", "rate limiter", "invoice export", "search index",
         "audit log", "user settings", "webhook retry", "backup job", "release notes",
         "error pages", "API paging", "theme switch", "email digest", "CSV import"]


def project(n_items, n_plans, seed=7):
    """Dummy issues: each depends on 0-2 earlier ones, mostly in its own area.
    Older items are more likely done."""
    rnd = random.Random(seed)
    areas = ["area/%s" % a for a in "abcdefgh"[:n_plans]]
    issues = []
    for i in range(1, n_items + 1):
        area = areas[(i - 1) % n_plans]
        same = [j for j in range(1, i) if areas[(j - 1) % n_plans] == area]
        deps = []
        if same and rnd.random() < 0.8:
            deps.append(rnd.choice(same[-4:]))
        if i > 3 and rnd.random() < 0.25:
            deps.append(rnd.randrange(1, i))
        age = 1 - i / n_items
        state = "closed" if rnd.random() < 0.15 + 0.6 * age else "open"
        assignees = ["dev"] if state == "open" and rnd.random() < 0.2 else []
        dep_list = ", ".join('"#%d"' % d for d in sorted(set(deps)))
        issues.append({
            "number": i, "state": state, "labels": [area], "assignees": assignees,
            "title": "%s %s" % (rnd.choice(VERBS), rnd.choice(NOUNS)),
            "body": "---\npm:\n  depends: [%s]\n---\n" % dep_list,
            "url": "https://forge.example/o/r/issues/%d" % i, "updated": "2026-10-20T00:00:00Z"})
    return areas, issues


def graph(n_items, n_plans):
    areas, issues = project(n_items, n_plans)

    class Fake(pmtrack.Forge):
        def issues(self):
            return [dict(i) for i in issues]

    with tempfile.TemporaryDirectory() as tmp:
        root = pathlib.Path(tmp)
        (root / "docs").mkdir()
        for a in areas:
            pid = a.split("/")[1]
            (root / "docs" / (pid + ".md")).write_text(
                "---\ntitle: Plan %s\npm:\n  id: %s\n  scope: {labels: [%s]}\n---\n" % (pid.upper(), pid, a))
        cfg = dict(pmtrack.DEFAULTS, url="https://forge.example", repo="o/r")
        proj = pmtrack.Project(root, cfg, Fake)
        proj.load_local()
        proj.compute()
        keys = [n.key for n in proj.local_issues()] + [p.key for p in proj.plans()]
        lines = pmtrack.mermaid_graph(proj, keys, cfg["graph_limit"])
    src = "\n".join(lines)
    nodes = sum(1 for l in lines if ":::" in l and "-->" not in l)
    edges = sum(1 for l in lines if "-->" in l or "-.-" in l)
    c = pmtrack.tally([proj.nodes[k] for k in keys if k.startswith("#")])
    stats = ("%d items (%s), %d plans → **%d nodes, %d links** drawn, %s characters of Mermaid "
             "(Forgejo's limit is %s)." % (n_items, pmtrack.summary(c), n_plans, nodes, edges,
                                          format(len(src), ","), format(MERMAID_LIMIT, ",")))
    return stats, lines


L = ["---", "title: Graph sample", "subtitle: The review's dependency graph at growing project sizes",
     "---", "", "# Graph sample", "",
     "Dummy projects, to see where the overview graph stops being readable",
     "(issue #10). Generated by `examples/graph_sample.py` with",
     "`pmtrack.mermaid_graph()`, exactly as the review draws it today. Past",
     "`graph_limit` (80) items, done items are left out.", "", pmtrack.LEGEND, ""]
for n, k, note in [(12, 2, "About where pmtrack itself is now."),
                   (40, 4, "A small team's quarter."),
                   (120, 6, "Past `graph_limit`, so done items are dropped.")]:
    stats, lines = graph(n, k)
    L += ["## %d items" % n, "", note + " " + stats, ""] + lines + [""]
(ROOT / "examples/graph-sample.md").write_text("\n".join(L))
print("wrote examples/graph-sample.md")
