"""Write examples/trend-sample.md: the review's trend chart drawn from dummy
history, to see how it looks before a project has any. Run from the repo root:
    python3 examples/trend_sample.py
"""
import datetime as dt
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
import pmtrack  # noqa: E402


def dates(n, start):
    d0 = dt.date.fromisoformat(start)
    return [(d0 + dt.timedelta(days=i)).isoformat() for i in range(n)]


def history(pcts, scopes, start):
    """Two snapshots a day; the trend keeps the last of each day."""
    out = []
    for day, p, t in zip(dates(len(pcts), start), pcts, scopes):
        for hour, q in (("08", max(p - 3, 0)), ("18", p)):
            out.append({"date": "%sT%s:00:00+00:00" % (day, hour),
                        "subsets": {"all": {"pct": q, "total": t}}})
    return out


SHORT = [4, 9, 9, 15, 13, 22, 31, 38]           # % done
SHORT_SCOPE = [20, 20, 20, 20, 24, 24, 24, 24]  # 10-20: four new items
LONG = [0, 2, 2, 5, 8, 8, 8, 11, 14, 18, 18, 21, 25, 25, 24, 27, 31, 35, 35, 35,
        40, 44, 47, 47, 52, 58, 61, 61, 66, 71]
SCOPE = [20, 20, 22, 22, 22, 24, 24, 24, 26, 26, 26, 26, 28, 28, 30, 30, 30, 30, 32, 32,
         32, 32, 32, 34, 34, 34, 34, 34, 34, 34]

L = ["---", "title: Trend sample", "subtitle: The review's trend chart, drawn from dummy history",
     "---", "", "# Trend sample", "",
     "Made-up data, to check how the trend chart in `progress/` looks once a",
     "project has some history. Generated by `examples/trend_sample.py` with",
     "`pmtrack.trend()`.", "",
     "The chart is a burn-up in items. % done mixes two things, work finishing",
     "and scope growing; counted in items, scope growth shows as the grey line",
     "stepping up, not as lost work.", "",
     "## Eight days", "",
     "Up to ten days, each label carries items done out of scope. On 10-20",
     "four items came in: the grey line steps up and the blue one keeps going.", ""]
L += pmtrack.trend(history(SHORT, SHORT_SCOPE, "2026-10-16"), "all")
L += ["", "## Thirty days", "", "Past ten days, labels are dates only; read values off the axis.", ""]
L += pmtrack.trend(history(LONG, SCOPE, "2026-09-23"), "all")
L += ["", "## One day", "", "With a single day of history the review shows this note instead:", ""]
L += pmtrack.trend(history([12], [20], "2026-10-23"), "all")
(ROOT / "examples/trend-sample.md").write_text("\n".join(L) + "\n")
print("wrote examples/trend-sample.md")
